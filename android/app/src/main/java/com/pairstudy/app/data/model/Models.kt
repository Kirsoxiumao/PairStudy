package com.pairstudy.app.data.model

data class ApiResponse<T>(val code: Int, val message: String, val data: T?)
data class User(val id: Long, val username: String, val nickname: String, val avatar: String, val groupId: Long?)
data class Auth(val token: String, val user: User)
data class LoginInput(val username: String, val password: String)
data class RegisterInput(val username: String, val password: String, val nickname: String)
data class BindInput(val inviteCode: String)
data class PairInfo(val groupId: Long?, val userA: User?, val userB: User?, val inviteCode: String?, val createdAt: String?, val boundAt: String?, val effectiveDate: String, val serverNow: String, val nextResetAt: String)
data class Category(val id: Long, val groupId: Long, val name: String, val iconName: String, val sortOrder: Int, val archived: Boolean)
data class CategoryInput(val name: String, val iconName: String = "book", val sortOrder: Int = 0)
data class CheckinImage(val id: Long, val imageUrl: String, val sortOrder: Int)
data class Checkin(val id: Long, val userId: Long, val nickname: String, val avatar: String, val role: String, val categoryId: Long, val categoryName: String, val content: String, val effectiveDate: String, val createdAt: String, val images: List<CheckinImage>)
data class CheckinInput(val categoryId: Long, val content: String, val imageIds: List<Long>, val requestId: String)
data class Page<T>(val items: List<T>, val page: Int, val size: Int, val total: Long, val hasMore: Boolean)
data class CalendarDay(val date: String, val selfChecked: Boolean, val partnerChecked: Boolean)
data class Profile(val user: User, val partner: User, val boundAt: String)
data class Statistics(val totalCheckins: Long, val monthDays: Long, val currentStreak: Long, val togetherDays: Long, val effectiveDate: String)
data class Upload(val id: Long, val imageUrl: String)
